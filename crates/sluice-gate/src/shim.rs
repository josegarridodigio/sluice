/// `sluice shim uninstall [--dir DIR]`.
pub fn uninstall(dir: Option<&Path>) -> ExitCode {
    let env = env_map();
    let cwd = current_dir();
    let dir = match shim_dir(dir, &env, &cwd) {
        Ok(d) => d,
        Err(e) => return error(&e),
    };
    let entries = match fs::read_dir(&dir) {
        Ok(e) => e,
        Err(e) if e.kind() == ErrorKind::NotFound => {
            println!(
                "sluice: shim: no shims in {} (nothing to do)",
                dir.display()
            );
            return ExitCode::SUCCESS;
        }
        Err(e) => return error(&format!("cannot read {}: {e}", dir.display())),
    };
    let mut removed = 0;
    let mut kept = Vec::new();
    let mut failed = Vec::new();
    for entry in entries.filter_map(Result::ok) {
        let path = entry.path();
        let name = entry.file_name().to_string_lossy().into_owned();
        if is_our_shim(&path) {
            match fs::remove_file(&path) {
                Ok(()) => removed += 1,
                Err(e) => failed.push(format!("{name}: {e}")),
            }
        } else {
            kept.push(name);
        }
    }
    kept.sort();
    // Only an empty directory goes (never anything Sluice did not write).
    let dir_removed = kept.is_empty() && failed.is_empty() && fs::remove_dir(&dir).is_ok();
    println!(
        "sluice: shim: removed {removed} shims from {}{}",
        dir.display(),
        if dir_removed {
            " (and the empty directory)"
        } else {
            ""
        }
    );
    if !kept.is_empty() {
        println!(
            "sluice: shim: kept files Sluice did not write: {}",
            kept.join(" ")
        );
    }
    if failed.is_empty() {
        ExitCode::SUCCESS
    } else {
        error(&format!("could not remove: {}", failed.join("; ")))
    }
}

/// Whether heavy commands go through the queue in this environment, and why.
fn mode(env: &EnvMap, user: &UserConfig) -> (bool, String) {
    if env.get(JOB_ENV_VAR).is_some_and(|v| !v.is_empty()) {
        return (false, format!("inside a Sluice job ({JOB_ENV_VAR} is set)"));
    }
    match env.get(SHIMS_VAR).and_then(|v| agent::parse_bool(v)) {
        Some(false) => return (false, format!("{SHIMS_VAR}=0")),
        Some(true) => return (true, format!("{SHIMS_VAR}=1")),
        None => {}
    }
    match agent::detect(
        env,
        &user.agent_detection.env_any_set,
        &user.agent_detection.env_any_equals,
    ) {
        Caller::Agent { rule } => (true, format!("agent session: {rule}")),
        Caller::Human => (false, "human session".to_owned()),
    }
}

/// One row of `sluice shim status`.
struct ShimRow {
    name: String,
    /// `current`, `stale` (another sluice path or an older script),
    /// `missing` or `foreign` (a file Sluice did not write).
    state: &'static str,
    real: Option<PathBuf>,
    /// The shim directory comes before the real binary in `PATH`.
    active: bool,
}

fn shim_state(path: &Path, expected: Option<&str>) -> &'static str {
    if fs::symlink_metadata(path).is_err() {
        "missing"
    } else if !is_our_shim(path) {
        "foreign"
    } else if expected.is_some_and(|want| fs::read_to_string(path).is_ok_and(|c| c == want)) {
        "current"
    } else {
        "stale"
    }
}

/// `sluice shim status [--dir DIR] [--json]`.
pub fn status(dir: Option<&Path>, json: bool) -> ExitCode {
    let env = env_map();
    let cwd = current_dir();
    let dir = match shim_dir(dir, &env, &cwd) {
        Ok(d) => d,
        Err(e) => return error(&e),
    };
    let user = load_user(&env, !json);
    let names = HeavyMatcher::from_config(&user.agent).shim_names();
    let sluice = sluice_binary().ok();
    let dir = fs::canonicalize(&dir).unwrap_or(dir);
    let position = path_position(&dir, &env, &cwd);
    // Resolve the real binaries exactly as a shim in this directory would.
    let mut resolve_env = env.clone();
    resolve_env.insert(SHIM_DIR_VAR.to_owned(), dir.display().to_string());
    let (queued, why) = mode(&env, &user);

    let rows: Vec<ShimRow> = names
        .iter()
        .map(|name| {
            let expected = sluice.as_ref().map(|s| script(&dir, s, name));
            let state = shim_state(&dir.join(name), expected.as_deref());
            let real = which::resolve(name, &resolve_env, &cwd, true).ok();
            let active = matches!(state, "current" | "stale")
                && position.is_some_and(|p| {
                    real.as_ref()
                        .and_then(|r| real_position(r, &env, &cwd))
                        .is_none_or(|r| p < r)
                });
            ShimRow {
                name: name.clone(),
                state,
                real,
                active,
            }
        })
        .collect();
    let mut unlisted: Vec<String> = fs::read_dir(&dir)
        .map(|entries| {
            entries
                .filter_map(Result::ok)
                .filter(|e| is_our_shim(&e.path()))
                .map(|e| e.file_name().to_string_lossy().into_owned())
                .filter(|n| !names.contains(n))
                .collect()
        })
        .unwrap_or_default();
    unlisted.sort();

    if json {
        let value = json!({
            "schema": 1,
            "dir": dir,
            "exists": dir.is_dir(),
            "in_path": position.is_some(),
            "path_index": position,
            "sluice": sluice,
            "this_shell": {"queue": queued, "reason": why},
            "shims": rows.iter().map(|r| json!({
                "name": r.name,
                "state": r.state,
                "real": r.real,
                "active": r.active,
            })).collect::<Vec<_>>(),
            "unlisted": unlisted,
        });
        println!(
            "{}",
            serde_json::to_string_pretty(&value).unwrap_or_default()
        );
        return ExitCode::SUCCESS;
    }
    print_status(&dir, position, (queued, &why), &rows, &unlisted);
    ExitCode::SUCCESS
}

/// The text form of `sluice shim status`.
fn print_status(
    dir: &Path,
    position: Option<usize>,
    (queued, why): (bool, &str),
    rows: &[ShimRow],
    unlisted: &[String],
) {
    println!(
        "shim dir:   {}{}",
        dir.display(),
        if dir.is_dir() { "" } else { " (not installed)" }
    );
    match position {
        Some(i) => println!("in PATH:    yes (entry {} of PATH)", i + 1),
        None => println!(
            "in PATH:    no (for agent shells: export PATH={}:\"$PATH\")",
            sh_quote(&dir.display().to_string())
        ),
    }
    println!(
        "this shell: {} ({why})",
        if queued {
            "heavy commands go through the queue"
        } else {
            "commands run directly"
        }
    );
    println!();
    let width = rows.iter().map(|r| r.name.len()).max().unwrap_or(4).max(4);
    println!(
        "{:<width$}  {:<8}  {:<6}  REAL BINARY",
        "NAME", "STATE", "ACTIVE"
    );
    for r in rows {
        println!(
            "{:<width$}  {:<8}  {:<6}  {}",
            r.name,
            r.state,
            if r.active { "yes" } else { "no" },
            r.real
                .as_ref()
                .map_or_else(|| "(not found)".to_owned(), |p| p.display().to_string())
        );
    }
    if !unlisted.is_empty() {
        println!(
            "\nshims of commands no longer in the heavy list (`sluice shim install` removes them): {}",
            unlisted.join(" ")
        );
    }
    if rows.iter().any(|r| matches!(r.state, "missing" | "stale")) {
        println!("\nrun `sluice shim install` to create or refresh the shims");
    }
}

