/// Variable that forces shims on (`1`) or off (`0`) regardless of agent
/// detection.
pub const SHIMS_VAR: &str = "SLUICE_SHIMS";

/// Every shim starts with exactly these bytes; only such files are ever
/// replaced or deleted by `install` and `uninstall`.
fn shim_prefix() -> String {
    format!("#!/bin/sh\n{SHIM_MARKER}\n")
}

/// Exit code of a usage or I/O error of `install`, `uninstall`, `status`.
const EXIT_ERROR: u8 = 1;

fn error(message: &str) -> ExitCode {
    eprintln!("sluice: shim: {message}");
    ExitCode::from(EXIT_ERROR)
}

/// `'text'` with embedded single quotes escaped, for a POSIX shell.
fn sh_quote(text: &str) -> String {
    format!("'{}'", text.replace('\'', r"'\''"))
}

/// The wrapper for `name` in `dir`, calling the `sluice` binary at `sluice`.
///
/// When that binary is gone the wrapper still runs the real command: it
/// drops from `PATH` every directory whose `<name>` is a Sluice shim and
/// execs `<name>` (the shell prints its usual `not found` and exits 127
/// when there is none), so it can never call itself.
pub fn script(dir: &Path, sluice: &Path, name: &str) -> String {
    let dir = sh_quote(&dir.display().to_string());
    let sluice = sh_quote(&sluice.display().to_string());
    let prefix = shim_prefix();
    format!(
        "{prefix}\
# Generated by Sluice (`sluice shim install`); `sluice shim uninstall` removes it.
# Routes '{name}' through the Sluice queue in agent sessions; runs it unchanged otherwise.
SLUICE_SHIM_DIR={dir}; export SLUICE_SHIM_DIR
if [ -x {sluice} ]; then
    exec {sluice} shim exec {name} -- \"$@\"
fi
# Sluice is gone: run the real '{name}', skipping every Sluice shim in PATH.
sluice_path=
set -f
IFS=:
for sluice_d in $PATH; do
    if [ -f \"${{sluice_d:-.}}/{name}\" ] && grep -q '^{SHIM_MARKER}$' \"${{sluice_d:-.}}/{name}\" 2>/dev/null; then
        continue
    fi
    sluice_path=${{sluice_path:+$sluice_path:}}$sluice_d
done
unset IFS sluice_d
set +f
PATH=$sluice_path; export PATH
unset sluice_path
exec {name} \"$@\"
"
    )
}

/// True when `path` is a regular file (not a symlink) written by Sluice.
fn is_our_shim(path: &Path) -> bool {
    let Ok(meta) = fs::symlink_metadata(path) else {
        return false;
    };
    if !meta.file_type().is_file() {
        return false;
    }
    let prefix = shim_prefix();
    let mut head = vec![0u8; prefix.len()];
    fs::File::open(path)
        .and_then(|mut f| f.read_exact(&mut head))
        .is_ok()
        && head == prefix.as_bytes()
}

fn env_map() -> EnvMap {
    sluice_gate_core::config::process_env()
}

fn load_user(env: &EnvMap, warn: bool) -> UserConfig {
    UserConfig::load(env).unwrap_or_else(|e| {
        if warn {
            eprintln!("sluice: warning: {e}; using the default settings");
        }
        UserConfig::default()
    })
}

/// The shim directory: `--dir` (made absolute), else `SLUICE_SHIM_DIR`,
/// else `$XDG_DATA_HOME/sluice/shims` or `~/.local/share/sluice/shims`.
fn shim_dir(arg: Option<&Path>, env: &EnvMap, cwd: &Path) -> Result<PathBuf, String> {
    let dir = arg
        .map(Path::to_path_buf)
        .or_else(|| {
            env.get(SHIM_DIR_VAR)
                .filter(|v| !v.is_empty())
                .map(PathBuf::from)
        })
        .or_else(|| which::default_shim_dir(env))
        .ok_or("cannot find the shim directory: HOME is not set; pass --dir")?;
    Ok(cwd.join(dir))
}

fn current_dir() -> PathBuf {
    std::env::current_dir().unwrap_or_else(|_| PathBuf::from("/"))
}

/// The running `sluice` binary, canonical.
fn sluice_binary() -> Result<PathBuf, String> {
    std::env::current_exe()
        .and_then(fs::canonicalize)
        .map_err(|e| format!("cannot locate the sluice binary: {e}"))
}

