/// Writes `content` to `path` atomically (temporary file + rename), mode 0755.
fn write_atomic(dir: &Path, path: &Path, content: &str) -> std::io::Result<()> {
    let tmp = dir.join(format!(
        ".sluice-shim-{}-{}.tmp",
        std::process::id(),
        path.file_name()
            .map_or_else(String::new, |n| n.to_string_lossy().into_owned())
    ));
    let result = (|| {
        let mut file = fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .mode(0o755)
            .open(&tmp)?;
        file.write_all(content.as_bytes())?;
        file.sync_all()?;
        fs::set_permissions(&tmp, fs::Permissions::from_mode(0o755))?;
        fs::rename(&tmp, path)
    })();
    if result.is_err() {
        let _ = fs::remove_file(&tmp);
    }
    result
}

/// Creates the shim directory when missing (mode 0700) and returns its
/// canonical path.
fn prepare_dir(dir: &Path) -> Result<PathBuf, String> {
    if !dir.exists() {
        fs::create_dir_all(dir).map_err(|e| format!("cannot create {}: {e}", dir.display()))?;
        fs::set_permissions(dir, fs::Permissions::from_mode(0o700))
            .map_err(|e| format!("cannot set the mode of {}: {e}", dir.display()))?;
    }
    match fs::canonicalize(dir) {
        Ok(d) if d.is_dir() => Ok(d),
        Ok(d) => Err(format!("{} is not a directory", d.display())),
        Err(e) => Err(format!("cannot use {}: {e}", dir.display())),
    }
}

/// Removes the Sluice shims of `dir` whose command is not in `names`
/// (no longer in the heavy list); returns their names, sorted.
fn prune(dir: &Path, names: &[String]) -> Vec<String> {
    let mut pruned = Vec::new();
    if let Ok(entries) = fs::read_dir(dir) {
        for entry in entries.filter_map(Result::ok) {
            let name = entry.file_name().to_string_lossy().into_owned();
            if !names.contains(&name)
                && is_our_shim(&entry.path())
                && fs::remove_file(entry.path()).is_ok()
            {
                pruned.push(name);
            }
        }
    }
    pruned.sort();
    pruned
}

/// What [`install_into`] did.
#[derive(Debug, Default)]
pub struct Installed {
    /// Canonical shim directory.
    pub dir: PathBuf,
    /// Shims written for the first time.
    pub created: usize,
    /// Sluice shims rewritten because they were stale.
    pub updated: usize,
    /// Shims already current.
    pub unchanged: usize,
    /// Foreign files replaced (only with `force`).
    pub replaced: usize,
    /// Names whose file Sluice did not write and was left alone.
    pub refused: Vec<String>,
    /// Sluice shims removed because their command left the heavy list.
    pub pruned: Vec<String>,
}

/// Creates or refreshes one shim per name of `names` in `dir`, pointing at
/// the `sluice` binary, and prunes Sluice shims of commands no longer listed.
/// Idempotent: a current shim is not rewritten. Files Sluice did not write
/// are never touched unless `force`.
///
/// # Errors
///
/// A message when the directory cannot be created or a shim cannot be
/// written.
pub fn install_into(
    dir: &Path,
    sluice: &Path,
    names: &[String],
    force: bool,
) -> Result<Installed, String> {
    let dir = prepare_dir(dir)?;
    let mut done = Installed::default();
    for name in names {
        let path = dir.join(name);
        let content = script(&dir, sluice, name);
        let exists = fs::symlink_metadata(&path).is_ok();
        if exists && !is_our_shim(&path) {
            if !force {
                done.refused.push(name.clone());
                continue;
            }
            if path.is_dir() {
                return Err(format!("{} is a directory", path.display()));
            }
            done.replaced += 1;
        } else if exists {
            if fs::read_to_string(&path).is_ok_and(|c| c == content) {
                done.unchanged += 1;
                continue;
            }
            done.updated += 1;
        } else {
            done.created += 1;
        }
        write_atomic(&dir, &path, &content)
            .map_err(|e| format!("cannot write {}: {e}", path.display()))?;
    }
    done.pruned = prune(&dir, names);
    done.dir = dir;
    Ok(done)
}

/// The directory `sluice shim install` and the session hook use when none is
/// given: `$SLUICE_SHIM_DIR`, else `$XDG_DATA_HOME/sluice/shims` or
/// `~/.local/share/sluice/shims`.
pub fn default_dir(env: &EnvMap, cwd: &Path) -> Result<PathBuf, String> {
    shim_dir(None, env, cwd)
}

/// Shell-quoted `text` (`'...'`), for lines written into shell files.
pub fn quote(text: &str) -> String {
    sh_quote(text)
}

/// The running `sluice` binary, canonical.
pub fn current_binary() -> Result<PathBuf, String> {
    sluice_binary()
}

/// `sluice shim install [--dir DIR] [--force]`.
pub fn install(dir: Option<&Path>, force: bool) -> ExitCode {
    let env = env_map();
    let cwd = current_dir();
    let dir = match shim_dir(dir, &env, &cwd) {
        Ok(d) => d,
        Err(e) => return error(&e),
    };
    let user = match UserConfig::load(&env) {
        Ok(u) => u,
        Err(e) => return error(&format!("{e}")),
    };
    let sluice = match sluice_binary() {
        Ok(p) => p,
        Err(e) => return error(&e),
    };
    let names = HeavyMatcher::from_config(&user.agent).shim_names();
    let done = match install_into(&dir, &sluice, &names, force) {
        Ok(d) => d,
        Err(e) => return error(&e),
    };
    let Installed {
        dir,
        created,
        updated,
        unchanged,
        replaced,
        refused,
        pruned,
    } = done;
    println!(
        "sluice: shim: {} shims in {} ({created} new, {updated} updated, {unchanged} unchanged{})",
        names.len() - refused.len(),
        dir.display(),
        if replaced > 0 {
            format!(", {replaced} foreign files replaced (--force)")
        } else {
            String::new()
        }
    );
    if !pruned.is_empty() {
        println!(
            "sluice: shim: removed shims no longer in the heavy list: {}",
            pruned.join(" ")
        );
    }
    if path_position(&dir, &env, &cwd).is_none_or(|i| i != 0) {
        println!(
            "Put the directory first in PATH for agent shells only, for example:\n  \
             export PATH={}:\"$PATH\" SLUICE_SHIMS=1\n\
             (see `sluice shim status` and docs/agents.md)",
            sh_quote(&dir.display().to_string())
        );
    }
    if refused.is_empty() {
        ExitCode::SUCCESS
    } else {
        error(&format!(
            "refused to overwrite files Sluice did not write: {} (use --force to replace them)",
            refused.join(" ")
        ))
    }
}

/// Canonical form of a `PATH` entry (an empty entry is `cwd`).
fn canonical_entry(entry: &str, cwd: &Path) -> Option<PathBuf> {
    let dir = if entry.is_empty() {
        cwd.to_path_buf()
    } else {
        cwd.join(entry)
    };
    fs::canonicalize(dir).ok()
}

/// Index of the first `PATH` entry that is `dir` (compared canonically, so
/// a symlink to it counts), if any.
fn path_position(dir: &Path, env: &EnvMap, cwd: &Path) -> Option<usize> {
    let dir = fs::canonicalize(dir).ok()?;
    env.get("PATH")?
        .split(':')
        .position(|e| canonical_entry(e, cwd).as_deref() == Some(dir.as_path()))
}

/// Index of the `PATH` entry that holds `real` (the binary a shim resolves to).
fn real_position(real: &Path, env: &EnvMap, cwd: &Path) -> Option<usize> {
    let parent = real.parent()?;
    env.get("PATH")?.split(':').position(|e| {
        let dir = if e.is_empty() {
            cwd.to_path_buf()
        } else {
            cwd.join(e)
        };
        dir == parent
    })
}

