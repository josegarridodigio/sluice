//! `sluice shim install|uninstall|status|exec`: shell shims that route the
//! heavy commands of agents that only have a shell (Codex, Cursor, Aider,
//! ...) through the shared queue.
//!
//! Design: `kb/sluice/design/command-control.md` section 5 (ADR-0010).
//!
//! A shim is a POSIX `sh` wrapper named after an executable of the heavy
//! list (`make`, `cargo`, `pnpm`, ...) that calls `sluice shim exec <name>
//! -- "$@"`. That command resolves the real binary further down `PATH`
//! (skipping the shim directory, wherever and however often it appears, and
//! every file that is itself a Sluice shim), then:
//!
//! - inside a Sluice job (`SLUICE_JOB` set), with `SLUICE_SHIMS=0`, in a
//!   human session (no agent detected and no `SLUICE_SHIMS=1`), for a
//!   subcommand that is not heavy (`docker ps`, `npm install`) or with a `-`
//!   argument (reads stdin): replaces itself with the real binary, so the
//!   command sees exactly the caller's stdin, stdout, stderr and terminal;
//! - when the command is exactly a gate of the repository's `.sluice.toml`
//!   (the same canonical-equality rule the guard uses), runs `sluice run
//!   <gate> -v` in this process: cache, coalescing and the queue;
//! - otherwise runs it as `sluice exec --label <words> -- <real> <args>`
//!   (in this process, no extra spawn): queued under the budget, output and
//!   exit code replayed byte for byte, stdin `/dev/null`.

